// One-click sustainability report in the structure an energy audit uses, printable to PDF.

import { Bot, FileCog, FileText, Printer, Sparkles } from 'lucide-react'
import { useState } from 'react'
import { aiReport, auditTrail, type Report } from '@/ai/client'
import { measuredSunshine } from '@/shared/openMeteo'
import { getSite } from '@/shared/site'
import { solarEstimate } from '@/sim/engine'
import { round } from '@/twin/energy'
import { templateReport } from '@/ai/reportTemplate'
import { reportFacts } from '@/ai/tools'
import { Button } from '@/components/ui/button'
import { Card, CardContent } from '@/components/ui/card'
import { ActivityLog } from '../components/ActivityLog'
import { EmptyState, PanelSkeleton } from '../components/states'

export default function Reports() {
  const [state, setState] = useState<'idle' | 'loading' | 'done'>('idle')
  const [report, setReport] = useState<Report | null>(null)

  async function generate() {
    setState('loading')
    const site = getSite()
    // Optional real inputs: the stored action log and the site's measured sunshine.
    const [trail, sun] = await Promise.all([
      auditTrail(30),
      site.location ? measuredSunshine(site.location.lat, site.location.lon).catch(() => null) : Promise.resolve(null),
    ])
    const solar = sun && solarEstimate(sun.kwhPerM2Day, 10, site.tariffPerKwh, site.gridKgPerKwh)
    const facts = reportFacts({
      auditTrail: trail,
      solar: solar && { kWp: 10, sunKwhPerM2Day: round(sun.kwhPerM2Day), yearKwh: round(solar.yearKwh, 0), yearCost: round(solar.yearCost, 0), yearCo2Tonnes: round(solar.yearCo2Kg / 1000, 1) },
    })
    try {
      setReport({ ...(await aiReport(facts)), source: 'ai' })
    } catch {
      setReport(templateReport(facts))
    }
    setState('done')
  }

  return (
    <div className="mx-auto max-w-4xl space-y-4">
      <div className="no-print flex flex-wrap items-center justify-between gap-2">
        <h1 className="flex items-center gap-2 text-xl font-semibold">
          <FileText className="size-5 text-highlight" aria-hidden /> Sustainability report
        </h1>
        <div className="flex gap-2">
          <Button onClick={generate} disabled={state === 'loading'}>
            <Sparkles aria-hidden /> {report ? 'Regenerate' : 'Generate report'}
          </Button>
          <Button variant="outline" onClick={() => window.print()} disabled={!report} title="Choose 'Save as PDF' in the print dialog">
            <Printer aria-hidden /> Download PDF
          </Button>
        </div>
      </div>

      {state === 'idle' && (
        <Card>
          <CardContent>
            <EmptyState icon={FileText} title="No report yet">
              <p className="max-w-md text-sm">
                The report uses this session's live record and a modelled week of your rooms. The AI writes the words; every number comes from the twin.
              </p>
            </EmptyState>
          </CardContent>
        </Card>
      )}
      {state === 'loading' && <PanelSkeleton rows={8} />}
      {state === 'done' && report && (
        <Card className="print-page">
          <CardContent className="space-y-6 px-8 py-6">
            <header className="space-y-1 border-b pb-4">
              <h2 className="text-2xl font-semibold">{report.title}</h2>
              <p className="flex items-center gap-1.5 text-sm text-muted-foreground">
                {report.source === 'ai' ? <Bot className="size-4" aria-hidden /> : <FileCog className="size-4" aria-hidden />}
                {report.source === 'ai' ? 'Written by AI from twin numbers, checked for invented figures' : 'Written by code (AI offline)'} · Generated by Pratibimb, Team Barfi
              </p>
            </header>
            {report.sections.map((s) => (
              <section key={s.heading} className="space-y-2">
                <h3 className="text-lg font-semibold">{s.heading}</h3>
                {s.paragraphs.map((p, i) => (
                  <p key={i} className="leading-relaxed">
                    {p}
                  </p>
                ))}
                {s.bullets.length > 0 && (
                  <ul className="list-disc space-y-1 pl-6">
                    {s.bullets.map((b, i) => (
                      <li key={i}>{b}</li>
                    ))}
                  </ul>
                )}
              </section>
            ))}
          </CardContent>
        </Card>
      )}
      <ActivityLog />
    </div>
  )
}
